/**
 * Transformation script: apply tinting-strength heuristics to paintDatabase.ts
 * Run with: node scripts/apply-tinting-strength.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const dbPath = join(__dirname, '../client/src/lib/paintDatabase.ts');

// Mirror of estimateTintingStrength — keep in sync with tintingStrength.ts
function estimate(name, category, brand) {
  const n = name.toLowerCase();

  if (category === 'transparent' && (n.includes('candy') || brand === 'createx-candy2o')) return 4.0;
  if (/phthalo|phthalocyanine|quinacridone|dioxazine|hansa|naphthol/.test(n)) return 3.5;
  if (n === 'black' || /\bjet black\b|carbon black|mars black/.test(n)) return 3.0;
  if (/cadmium|crimson|magenta|alizarin/.test(n)) return 2.0;
  if (/ultramarine|cobalt|prussian|cerulean/.test(n)) return 1.8;
  if (category === 'transparent') return 1.5;
  if (/oxide|umber|sienna|ochre|earth|raw |burnt /.test(n)) return 0.7;
  if (/\bwhite\b|titanium/.test(n)) return 0.4;
  if (category === 'metallic' || category === 'pearl') return 0.6;
  if (category === 'fluorescent') return 0.8;
  return 1.0;
}

const src = readFileSync(dbPath, 'utf8');
const defaults = [];

// Match every paint object literal on a single line
const paintRe = /(\{ code: '([^']+)', name: '([^']+)', brand: '([^']+)', category: '([^']+)', rgb: \[[^\]]+\], opacity: [\d.]+), tintingStrength: 1 (\})/g;

const result = src.replace(paintRe, (match, prefix, code, name, brand, category, suffix) => {
  const ts = estimate(name, category, brand);
  if (ts === 1.0) defaults.push({ code, name, brand, category });
  return `${prefix}, tintingStrength: ${ts}, tintingStrengthSource: 'estimated' ${suffix}`;
});

writeFileSync(dbPath, result, 'utf8');

console.log(`Updated paintDatabase.ts`);
console.log(`Paints falling through to default 1.0: ${defaults.length}`);

// Write the review queue
const mdLines = [
  '# Paints Needing Tinting-Strength Review',
  '',
  'These paints fell through to the default `tintingStrength: 1.0` because the',
  'name-based heuristic in `tintingStrength.ts` did not match any specific rule.',
  'Review each one and either update the heuristic or set a hand-tuned value.',
  '',
  '| Code | Name | Brand | Category |',
  '|------|------|-------|----------|',
  ...defaults.map(p => `| ${p.code} | ${p.name} | ${p.brand} | ${p.category} |`),
  '',
  `_Generated by \`scripts/apply-tinting-strength.mjs\` — ${defaults.length} entries_`,
];

const mdPath = join(__dirname, '../paints_needing_review.md');
writeFileSync(mdPath, mdLines.join('\n') + '\n', 'utf8');
console.log(`Wrote paints_needing_review.md (${defaults.length} entries)`);
